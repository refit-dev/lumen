/**
 * Resolve both internal and external customer IDs for a given customer identifier
 * @param merchantId The merchant ID
 * @param customerIdentifier The customer identifier (could be internal ID or external ID)
 * @param isExternalId Whether the identifier is an external customer ID
 * @returns Object containing both internal and external customer IDs, or null if customer not found
 */
async function resolveCustomerIds(
  merchantId: string,
  customerIdentifier: string,
  isExternalId: boolean = false
): Promise<{ internalId: string; externalId: string | null } | null> {
  try {
    let customer;

    if (isExternalId) {
      // Looking up by external customer ID
      customer = await db
        .select({
          id: customers.id,
          externalCustomerId: customers.externalCustomerId,
        })
        .from(customers)
        .where(
          and(
            eq(customers.merchantId, merchantId),
            eq(customers.externalCustomerId, customerIdentifier),
            isNull(customers.deletedAt)
          )
        )
        .limit(1);
    } else {
      // Looking up by internal customer ID
      customer = await db
        .select({
          id: customers.id,
          externalCustomerId: customers.externalCustomerId,
        })
        .from(customers)
        .where(
          and(
            eq(customers.merchantId, merchantId),
            eq(customers.id, customerIdentifier),
            isNull(customers.deletedAt)
          )
        )
        .limit(1);
    }

    if (customer.length === 0) {
      return null; // Customer not found
    }

    return {
      internalId: customer[0].id,
      externalId: customer[0].externalCustomerId,
    };
  } catch (error) {
    logger.error(
      `Failed to resolve customer IDs for ${customerIdentifier}:`,
      error
    );
    return null;
  }
}

