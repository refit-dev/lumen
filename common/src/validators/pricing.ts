// Main price DSL schema
export const priceDSLSchemaZod = z
  .object({
    dsl_version: z
      .number()
      .int()
      .positive()
      .refine((val) => val >= 1, {
        message:
          "Invalid DSL version. Must be a positive integer (currently supported: 1)",
      }),
    components: z
      .array(
        z.union([
          fixedPriceComponentSchema,
          perUnitPriceComponentSchema,
          usageBasedPriceComponentSchema,
        ])
      )
      .min(1, "At least one component is required in the pricing structure"),
  })
  .superRefine((data, ctx) => {
    // Check for duplicate component_names (case-insensitive)
    const componentNames = new Set<string>();
    const duplicateNames: string[] = [];

    for (const component of data.components) {
      if (component.component_name) {
        const normalizedName = component.component_name.toLowerCase().trim();
        if (componentNames.has(normalizedName)) {
          duplicateNames.push(component.component_name);
        } else {
          componentNames.add(normalizedName);
        }
      }
    }

    if (duplicateNames.length > 0) {
      ctx.addIssue({
        code: z.ZodIssueCode.custom,
        message: `Duplicate component names found: ${duplicateNames.join(", ")}. Each component must have a unique name.`,
        path: ["components"],
      });
    }
  });

// Type aliases for TypeScript - derived from Zod schemas
export type FixedPriceComponentSchemaType = Omit<
  z.infer<typeof fixedPriceComponentSchema>,
  "component_id"
> & {
  component_id: string;
} & Partial<{ bill_immediately: boolean }>;

export type PerUnitPriceComponentSchemaType = Omit<
  z.infer<typeof perUnitPriceComponentSchema>,
  "component_id"
> & {
  component_id: string;
  metric_id?: string;
  num_seats?: number;
} & Partial<{ bill_immediately: boolean }>;

export type UsageBasedPriceComponentSchemaType = Omit<
  z.infer<typeof usageBasedPriceComponentSchema>,
  "component_id"
> & {
  component_id: string;
} & Partial<{ bill_immediately: boolean }>;

export type PriceComponentSchemaType =
  | FixedPriceComponentSchemaType
  | PerUnitPriceComponentSchemaType
  | UsageBasedPriceComponentSchemaType;

export type PriceDSLSchemaType = {
  dsl_version: number;
  components: PriceComponentSchemaType[];
};

export type PriceDSLSchemaCreate = z.infer<typeof priceDSLSchemaZod>;
