import { z } from "zod";
import { RRule } from "rrule";
import { ID_PREFIXES } from "../db/utils";

/**
 * Zod validators for Price DSL
 */

// Validate that a string is in RRULE format without TZID and has supported frequency
// Example: "RRULE:FREQ=MONTHLY;BYMONTHDAY=1"
// TZID should *not* be in the recurrence rule as per RFC
const rruleSchema = z.string().refine(
  (value) => {
    try {
      // Check that TZID is NOT present
      if (value.includes("TZID=")) {
        return false;
      }

      // Ensure it starts with RRULE: prefix
      if (!value.startsWith("RRULE:")) {
        return false;
      }

      // Try to parse the rule - this will throw if invalid
      const rule = RRule.parseString(value);

      // Validate frequency is supported
      const supportedFrequencies = [
        RRule.MONTHLY,
        RRule.YEARLY,
        RRule.WEEKLY,
        RRule.DAILY,
      ];
      if (rule.freq == null || !supportedFrequencies.includes(rule.freq)) {
        return false;
      }

      // Warn about potentially problematic patterns
      if (rule.freq === RRule.DAILY && !rule.count && !rule.until) {
        return false;
      }

      return true;
    } catch (error) {
      return false;
    }
  },
  {
    message:
      "Invalid RRULE format. Must be a valid RRULE string starting with 'RRULE:' and must NOT contain TZID parameter. Supported frequencies: MONTHLY, YEARLY, WEEKLY, DAILY. Daily billing requires COUNT or UNTIL.",
  }
);

// Fixed price component schema
export const fixedPriceComponentSchema = z.object({
  component_id: z
    .string()
    .optional()
    .refine((val) => val === undefined, {
      message:
        "component_id should not be provided by users. It will be auto-generated by the system.",
    }),
  component_name: z
    .string()
    .min(1, "Component name is required")
    .max(100, "Component name must be 100 characters or less")
    .optional(), // Optional but validated when provided
  type: z.literal("fixed"),
  label: z
    .string()
    .min(1, "Label is required for invoice display")
    .max(200, "Label must be 200 characters or less"),
  amount_cents: z
    .number()
    .int()
    .min(0, "Amount must be a non-negative integer"),
  recurrence_rule: rruleSchema,
  bill_immediately: z.boolean().optional().default(true),
});

// Per-unit price component schema
export const perUnitPriceComponentSchema = z.object({
  component_id: z
    .string()
    .optional()
    .refine((val) => val === undefined, {
      message:
        "component_id should not be provided by users. It will be auto-generated by the system.",
    }),
  component_name: z
    .string()
    .min(1, "Component name is required")
    .max(100, "Component name must be 100 characters or less")
    .optional(), // Optional but validated when provided
  type: z.literal("per_unit"),
  unit_label: z
    .string()
    .min(1, "Unit label is required for invoice display")
    .max(50, "Unit label must be 50 characters or less"),
  label: z
    .string()
    .min(1, "Label is required for invoice display")
    .max(200, "Label must be 200 characters or less"),
  amount_cents: z
    .number()
    .int()
    .min(0, "Amount must be a non-negative integer"),
  // Optional minimum number of units for billing (e.g., minimum seats)
  num_seats: z
    .number()
    .int()
    .min(0, "Minimum seats must be at least 0")
    .optional(),
  // Metric ID for seat counting (auto-generated if not provided)
  metric_id: z
    .string()
    .min(5, "Metric ID must be at least 5 characters long")
    .max(100, "Metric ID must be 100 characters or less")
    .refine((val) => val.startsWith(ID_PREFIXES.metric), {
      message: `Metric ID must start with '${ID_PREFIXES.metric}' prefix`,
    })
    .optional(),
  recurrence_rule: rruleSchema,
  bill_immediately: z.boolean().optional().default(true),
});

